 const item={colors:['Nero'],sizes:['S','M'],tags:[],stock:0,image:'/delu-logo.svg',active:true,fabrics:['Viscosa'],attributes:{values:{length:['Midi'],model:['A tubino'],occasion:['Da sera','Da cerimonia'],craft:['Ricamato a mano']},compositions:{Composizione:[{material:'Viscosa',percent:95},{material:'Elastan',percent:5}]}}}
 await page.route('**/api/products',r=>r.fulfill({json:[{...item,id:'dress-1',name:'Abito sera',price:89,category:'Abiti'},{...item,id:'dress-2',name:'Abito mini',price:60,category:'Abiti',attributes:{values:{length:['Mini'],occasion:['Casual']},compositions:{}}},{...item,id:'trousers-1',name:'Pantaloni palazzo',price:79,category:'Pantaloni',attributes:{values:{model:['Palazzo'],length:['Lungo'],fit:['Slim fit'],rise:['Vita alta']},compositions:{}}}]}))
 await page.goto('/shop?category=Abiti')
 await expect(page.locator('.catalog-categories button.active')).toHaveCSS('color','rgb(255, 255, 255)')
 await page.locator('.ds-toolbar>button').click()
 const filters=page.locator('#catalog-filters')
 await expect(filters.locator('fieldset')).toHaveCount(6)
 await expect(filters.getByText('Modello',{exact:true})).toHaveCount(0)
 await filters.getByRole('checkbox',{name:'Da sera',exact:false}).check()
 await filters.getByRole('checkbox',{name:'Casual',exact:false}).check()
 await expect(page.locator('.ds-products .ds-product')).toHaveCount(2)
 await filters.getByRole('checkbox',{name:'Midi',exact:false}).check()
 await expect(page.locator('.ds-products .ds-product')).toHaveCount(1)
 await filters.getByRole('spinbutton',{name:'Prezzo Max'}).fill('80')
 await expect(page.locator('.ds-products .ds-product')).toHaveCount(0)
 await page.locator('.catalog-reset').click()
 await expect(page.locator('.ds-products .ds-product')).toHaveCount(2)
 await page.locator('.catalog-categories').getByRole('button',{name:'Pantaloni',exact:true}).click()
 await expect(filters.locator('fieldset')).toHaveCount(6)
 await expect(filters.getByText('Modello',{exact:true})).toBeVisible()
 await expect(filters.getByText('Vestibilità',{exact:true})).toHaveCount(0)
 await expect(filters.getByText('Altezza vita',{exact:true})).toHaveCount(0)
 await expectNoHorizontalOverflow(page)
 await page.goto('/product/dress-1')
 await page.getByRole('tab',{name:'Materiali e cura',exact:true}).click()
 await expect(page.getByRole('tabpanel')).toContainText('Viscosa 95% · Elastan 5%')
